#!/usr/bin/env python3
"""Generate supabase/seed.sql from the Modern Furniture Pacific site data.

Reads the site repo's products.json (35 products, 98 variants, 183 images)
and emits a single idempotent seed file: categories/products/business_info
are upserted by their natural keys, and each product's variants/images are
deleted then re-inserted, so re-running the seed is safe.

Row ids are deterministic UUIDv5 values derived from the natural keys
(handle / slug), so foreign keys line up without a round-trip to the DB.

Usage:
    python3 scripts/generate_seed.py [--source PATH] [--output PATH]

Defaults:
    --source  ../modern-furniture-pacific/src/data/products.json
              (the site repo next to this one; falls back to the VM path
              ~/workspace/modern-furniture-pacific-rebuild/site/src/data/products.json)
    --output  supabase/seed.sql
"""

import argparse
import json
import os
import re
import sys
import uuid

NS = uuid.NAMESPACE_URL


def sql_str(value):
    """Render a Python value as a SQL literal (NULL for None/empty str)."""
    if value is None:
        return "NULL"
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, (int, float)):
        return repr(value)
    return "'" + str(value).replace("'", "''") + "'"


def sql_text_array(values):
    if not values:
        return "'{}'::text[]"
    inner = ",".join('"' + str(v).replace('"', '\\"') + '"' for v in values)
    return "'{" + inner + "}'::text[]"


def slugify(name):
    slug = name.strip().lower()
    slug = re.sub(r"[^a-z0-9]+", "-", slug).strip("-")
    return slug


def cat_uuid(slug):
    return str(uuid.uuid5(NS, f"mfp:category:{slug}"))


def product_uuid(handle):
    return str(uuid.uuid5(NS, f"mfp:product:{handle}"))


def child_uuid(kind, handle, position):
    return str(uuid.uuid5(NS, f"mfp:{kind}:{handle}:{position}"))


DEFAULT_SOURCES = [
    os.path.join(os.path.dirname(__file__), "..", "..",
                 "modern-furniture-pacific", "src", "data", "products.json"),
    os.path.expanduser("~/workspace/modern-furniture-pacific-rebuild/"
                       "site/src/data/products.json"),
]


def find_source(explicit):
    if explicit:
        return explicit
    for cand in DEFAULT_SOURCES:
        if os.path.exists(cand):
            return cand
    return DEFAULT_SOURCES[0]


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--source", default=None,
                    help="path to the site products.json")
    ap.add_argument("--output", default=None,
                    help="where to write seed.sql")
    args = ap.parse_args()

    repo_root = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
    source = find_source(args.source)
    output = args.output or os.path.join(repo_root, "supabase", "seed.sql")

    if not os.path.exists(source):
        print(f"ERROR: products.json not found at {source}", file=sys.stderr)
        print("Pass --source with the path to the site repo's "
              "src/data/products.json", file=sys.stderr)
        return 1

    with open(source, encoding="utf-8") as fh:
        data = json.load(fh)

    products = data["products"]
    business = data.get("business", {})

    lines = []
    lines.append("-- Modern Furniture Pacific — seed data")
    lines.append(f"-- Generated by scripts/generate_seed.py from {source}")
    lines.append("-- Idempotent: safe to re-run. Counts: "
                 f"{len(products)} products.")
    lines.append("")

    # ---- categories (distinct product `category` values) ------------------
    categories = sorted({p["category"] for p in products})
    lines.append("-- categories ------------------------------------------------")
    for name in categories:
        slug = slugify(name)
        lines.append(
            "insert into public.categories (id, name, slug) values "
            f"({sql_str(cat_uuid(slug))}, {sql_str(name)}, {sql_str(slug)}) "
            "on conflict (slug) do update set name = excluded.name;"
        )
    lines.append("")

    # ---- business_info (single row) ---------------------------------------
    lines.append("-- business_info ---------------------------------------------")
    showrooms_json = json.dumps(business.get("showrooms", []),
                                ensure_ascii=False)
    lines.append(
        "insert into public.business_info "
        "(id, name, tagline, phone, whatsapp, email, hours, showrooms, "
        "source_url) values "
        f"({sql_str(str(uuid.uuid5(NS, 'mfp:business:info')))}, "
        f"{sql_str(business.get('name'))}, "
        f"{sql_str(business.get('tagline'))}, "
        f"{sql_text_array(business.get('phone', []))}, "
        f"{sql_str(business.get('whatsapp'))}, "
        f"{sql_str(business.get('email'))}, "
        f"{sql_str(business.get('hours'))}, "
        f"{sql_str(showrooms_json)}::jsonb, "
        f"{sql_str(business.get('source'))}) "
        "on conflict (id) do update set "
        "name = excluded.name, tagline = excluded.tagline, "
        "phone = excluded.phone, whatsapp = excluded.whatsapp, "
        "email = excluded.email, hours = excluded.hours, "
        "showrooms = excluded.showrooms, source_url = excluded.source_url;"
    )
    lines.append("")

    # ---- products, variants, images ---------------------------------------
    # Display order is the JSON order (the order the shop page lists
    # products in). Rows below are written alphabetically for a stable
    # diff; `position` carries the display order.
    position_by_handle = {p["handle"]: i for i, p in enumerate(products)}
    n_variants = 0
    n_images = 0
    for p in sorted(products, key=lambda x: x["handle"]):
        handle = p["handle"]
        pid = product_uuid(handle)
        cat_id = cat_uuid(slugify(p["category"]))
        desc = p.get("description") or None  # empty string -> NULL

        lines.append(f"-- {handle} ------------------------------------------------")
        lines.append(
            "insert into public.products (id, shopify_id, handle, title, "
            "original_title, type, category_id, collections, is_new, "
            "is_best_seller, vendor, description, price_min, price_max, "
            "in_stock, original_url, position) values "
            f"({sql_str(pid)}, {sql_str(p['id'])}, {sql_str(handle)}, "
            f"{sql_str(p['title'])}, {sql_str(p.get('originalTitle'))}, "
            f"{sql_str(p.get('type'))}, {sql_str(cat_id)}, "
            f"{sql_text_array(p.get('collections', []))}, "
            f"{sql_str(bool(p.get('isNew')))}, "
            f"{sql_str(bool(p.get('isBestSeller')))}, "
            f"{sql_str(p.get('vendor'))}, {sql_str(desc)}, "
            f"{sql_str(p['priceMin'])}, {sql_str(p['priceMax'])}, "
            f"{sql_str(bool(p.get('inStock')))}, {sql_str(p.get('url'))}, "
            f"{position_by_handle[handle]}) "
            "on conflict (handle) do update set "
            "shopify_id = excluded.shopify_id, title = excluded.title, "
            "original_title = excluded.original_title, "
            "type = excluded.type, category_id = excluded.category_id, "
            "collections = excluded.collections, "
            "is_new = excluded.is_new, "
            "is_best_seller = excluded.is_best_seller, "
            "vendor = excluded.vendor, description = excluded.description, "
            "price_min = excluded.price_min, "
            "price_max = excluded.price_max, "
            "in_stock = excluded.in_stock, "
            "original_url = excluded.original_url, "
            "position = excluded.position, "
            "updated_at = now();"
        )

        lines.append(
            f"delete from public.product_variants where product_id = "
            f"{sql_str(pid)};")
        for pos, v in enumerate(p.get("variants", [])):
            n_variants += 1
            lines.append(
                "insert into public.product_variants "
                "(id, product_id, option, price, available, position) values "
                f"({sql_str(child_uuid('variant', handle, pos))}, "
                f"{sql_str(pid)}, {sql_str(v['option'])}, "
                f"{sql_str(v['price'])}, {sql_str(bool(v.get('available')))}, "
                f"{pos});")

        lines.append(
            f"delete from public.product_images where product_id = "
            f"{sql_str(pid)};")
        for pos, path in enumerate(p.get("images", [])):
            n_images += 1
            lines.append(
                "insert into public.product_images "
                "(id, product_id, path, position, is_premium) values "
                f"({sql_str(child_uuid('image', handle, pos))}, "
                f"{sql_str(pid)}, {sql_str(path)}, {pos}, false);")
        lines.append("")

    with open(output, "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines))

    print(f"source:    {source}")
    print(f"output:    {output}")
    print(f"products:  {len(products)}")
    print(f"categories:{len(categories)} ({', '.join(categories)})")
    print(f"variants:  {n_variants}")
    print(f"images:    {n_images}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
